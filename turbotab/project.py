"""
turbotab.project — the minimal `AnalysisProject`.

This is the container `st.session_state` is standing in for today: what is
currently true about one analysis. It holds a dataframe handle, the target, an
append-only list of decisions, and the findings last computed. It computes
nothing — `turbotab.engine` does that — so this module imports neither the
engine nor pandas' analysis surface, and can be reasoned about on its own.

Three commitments carried over from the transition documents:

**Row identity is index labels, never positions** (`TRANSITION_PLAN.md` §02.2).
The lockbox already stores labels; the split block stores positions; page 07
reads the second against a re-fetched frame. They agree only while the index is
a pristine `RangeIndex`, which cohort filtering, row-dropping repairs and joins
all break. This project picks labels and says so in one place —
:meth:`AnalysisProject.rows`, which uses ``.loc`` and refuses ``.iloc``.

**Decisions are append-only** (`ARCHITECTURE.md` §03). The record is what
happened; the project is what is currently true. Changing the target does not
edit the earlier decision, it appends a new one — otherwise "the target was
chosen before exploration" stops being a statement anyone can check.

**Persist decisions and inputs; regenerate derivatives.** An earlier version of
this docstring read ``_NEVER_PERSIST`` as a prohibition on writing anything to
disk. It is a **drop-list**: `utils/session_manager.py` already saves a session
as a zip of JSON and parquet — config, the ledger, provenance, the sealed
lockbox, cohort runs — and drops trained models, fitted pipelines, splits,
metrics and profiles because they are unsafe to pickle or cheap to rebuild
(*"regenerated by re-running Page 06"*). Durability is `turbotab.archive`, which
ports that schema rather than inventing one. What must never be persisted is
**participant data inside the decision record**, and
:func:`turbotab.archive.assert_no_participant_data` is the check that makes that
rule testable rather than remembered.

**The identity barrier** (`T0-ID-001`). Rows acquire identities when the lockbox
is sealed. Repairs that change what a row *is* — ``promote_header``,
``melt_repeated`` — may only run before that; repairs that merely remove rows
preserve the survivors' labels and may run either side. The project owns the
lockbox, so the project is the thing that can refuse: see
:meth:`AnalysisProject.check_repair_allowed`.
"""
from __future__ import annotations

import hashlib
import uuid
from dataclasses import dataclass, field
from datetime import datetime, timezone
from typing import Any, Dict, List, Optional, Sequence, Tuple

import pandas as pd

# Repairs that rebuild what a row IS, rather than removing rows. After the
# barrier these cannot preserve identity even in principle: `promote_header`
# re-reads the frame from a different starting row, and `melt_repeated` turns
# one row into several. The other renumbering kinds (`drop_empty_rows`,
# `drop_rows`) keep the surviving rows' labels and are allowed on either side.
PRE_BARRIER_ONLY_FIXES = frozenset({"promote_header", "melt_repeated"})

