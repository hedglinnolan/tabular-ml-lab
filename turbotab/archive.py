"""
turbotab.archive — durability, using `utils/session_manager.py`'s schema.

**Ported, not redesigned.** `session_manager` already solves this and already
handles the hardest member: the sealed lockbox, whose labels must survive a
save/restore *verbatim* because re-drawing them with a lost non-default fraction
would silently change the test set every prior result was scored on.

The contract it encodes, which `_NEVER_PERSIST` states as a drop-list rather
than a prohibition:

> **Persist decisions and inputs; regenerate derivatives.**

Trained models, fitted pipelines, splits, metrics and profiles are dropped
because they are unsafe to pickle or cheap to rebuild — the comments in
`session_manager` say so directly: *"regenerated by re-running Page 06"*,
*"regenerated from raw_data + split_config"*. `turbotab.cascade` already knows
which keys are derivatives, so the drop-list is derived from the graph instead
of maintained by hand.

Same members, same names, same schema version, so an archive written here is
readable there and vice versa:

    manifest.json     schema_version, saved_at, saved_keys, skipped_keys, members
    config.json       target, task type, per-model pipeline SPECS, plain config
    lockbox.json      sealed labels + every disclosure the chip reports
    cohort.json       the active cohort filter, by row label
    provenance.json   the decision record
    data/*.parquet    the tables

**The guard.** :func:`assert_no_participant_data` checks the operational meaning
of "never persist participant data": no cell value from the loaded frame appears
anywhere in the serialized *project*. The frame itself travels as parquet, which
is the user saving their own session; the decision record must not become a
second, unmanaged copy of it.
"""
from __future__ import annotations

import io
import json
import zipfile
from datetime import datetime, timezone
from typing import Any, Dict, Iterable, List, Mapping, Optional, Set, Tuple

import pandas as pd

# Written by `utils/session_manager.py`. Kept identical on purpose: the two
# doors must read each other's archives, and a private schema would fork
# durability the way a private engine would fork results.
SAVE_SCHEMA_VERSION = "2.1"
ACCEPTED_SCHEMA_VERSIONS = {"2.0", "2.1"}


class ArchiveError(Exception):
    """The archive cannot be written or read honestly."""


def _looks_like_pickle(head: bytes) -> bool:
    """`session_manager` refuses pickles outright; so does this.

    A restore that executes arbitrary code is a different security posture from
    a restore that parses JSON, and the app has chosen the second.
    """
    return head[:1] in (b"\x80", b"]", b"}") and b"{" not in head[:4]


def _plain_label(x: Any) -> Any:
    """Coerce one index label exactly as `session_manager` does.

    Not cosmetic. `json.dumps(default=str)` turns a numpy int into a *string*,
    and a string label no longer matches an integer index on restore — a silent
    all-False membership test, i.e. a lockbox that quarantines nothing.
    """
    if isinstance(x, bool):
        return str(x)
    if isinstance(x, int):
        return x
    if hasattr(x, "item"):
        v = x.item()
        return v if isinstance(v, int) else str(v)
    return str(x)


def _json_safe(obj: Any) -> Any:
    try:
        json.dumps(obj)
        return obj
    except (TypeError, ValueError):
        pass
    if isinstance(obj, dict):
        return {str(k): _json_safe(v) for k, v in obj.items()}
    if isinstance(obj, (list, tuple)):
        return [_json_safe(v) for v in obj]
    return str(obj)


# ─────────────────────────────────────────────────────────────────────────────
# The guard
# ─────────────────────────────────────────────────────────────────────────────

def _is_bare_integer(text: str) -> bool:
    return text.lstrip("-").isdigit()


# Keys whose array values are row IDENTITIES rather than data. The lockbox and
# the cohort filter both hold rows by index label, which is the whole point of
# `T0-ID-001`, so those arrays are excluded from leak-checking. Their contents
# are references to rows, not the contents of rows.
_IDENTITY_KEYS = frozenset({"labels", "order"})


def _leaves(blob: str) -> Tuple[Set[str], List[str]]:
    """Scalars in the serialized project, split into exact values and prose.

    Parsed rather than substring-searched over the raw text. Searching the raw
    JSON treats the row-label array as a haystack — with labels `0..99` present,
    every two-digit cell value "appears" in the record and the guard cries leak
    on any dataset. Comparing values to values removes that.

    Two sets, because leaks arrive two ways:

    * **exact** — a value stored as a field, e.g. a cohort's filter value;
    * **prose** — a value quoted inside a sentence, which is how engine findings
      leak (*"Found 999 (4x)"*, *"e.g. '107 kg'"*). Those need a substring
      search, but only within string leaves, never across the whole document.

    Arrays under an identity key are skipped entirely: the lockbox and cohort
    hold rows by index label, and a reference to a row is not the contents of
    one.
    """
    exact: Set[str] = set()
    prose: List[str] = []

    def walk(node: Any, under_identity: bool = False) -> None:
        if isinstance(node, dict):
            for k, v in node.items():
                walk(v, under_identity or str(k) in _IDENTITY_KEYS)
        elif isinstance(node, (list, tuple)):
            for v in node:
                walk(v, under_identity)
        elif node is not None and not isinstance(node, bool) and not under_identity:
            text = str(node).strip()
            exact.add(text)
            if isinstance(node, str) and len(text) > 12:
                prose.append(text)

    try:
        walk(json.loads(blob))
    except (ValueError, TypeError) as exc:
        raise ArchiveError(
            "The guard needs the serialized project as one JSON document; use "
            "archive.serialized_json(project)."
        ) from exc
    return exact, prose


def _frame_cell_values(df: pd.DataFrame, max_per_column: int = 400) -> Set[str]:
    """Distinct cell values, as text, for leak-checking.

    Two exclusions, both because a match would be a coincidence rather than a
    leak:

    * **Column names.** A project necessarily names its columns; "the target is
      `glucose`" is a decision, not a participant's data.
    * **Bare integers.** A record legitimately states counts — 140 rows, 100 in
      the cohort, seed 42 — and those collide with any integer-valued column.
      Excluding them costs nothing, because a single integer is not a
      participant either way; what makes an integer identifying is appearing
      *alongside* other values from the same row, which is what
      :func:`assert_no_row_is_recoverable` checks.
    """
    values: Set[str] = set()
    names = {str(c) for c in df.columns}
    for pos in range(len(df.columns)):
        col = df.iloc[:, pos]
        for v in col.dropna().unique()[:max_per_column]:
            text = str(v).strip()
            if len(text) >= 3 and text not in names and not _is_bare_integer(text):
                values.add(text)
    return values


def assert_no_row_is_recoverable(
    serialized: Mapping[str, Any] | str,
    df: pd.DataFrame,
    *,
    allow: Iterable[str] = (),
    max_rows: int = 500,
    threshold: int = 3,
) -> None:
    """No single row may be reconstructible from the serialized project.

    The backstop to :func:`assert_no_participant_data`, and the sharper
    statement of what "participant data" means. One value in isolation is a
    fact about a column — a sentinel code, a category name, a count. What makes
    data *personal* is several values from the **same row** appearing together,
    because that is a person.

    This catches leaks the literal check excludes by design, notably bare
    integers: `140` alone is a row count, but `140` next to `P0001` and `6.4` is
    a participant.
    """
    blob = serialized if isinstance(serialized, str) else json.dumps(
        serialized, default=str)
    exact, prose = _leaves(blob)
    allowed = {str(a) for a in allow}
    names = {str(c) for c in df.columns}
    for label in list(df.index)[:max_rows]:
        present = 0
        for value in df.loc[label]:
            if pd.isna(value):
                continue
            token = str(value).strip()
            # Same exclusions as the value check, for the same reasons: a bare
            # integer collides with the counts a record must state ("100 of 140
            # rows"), a column name is not data, and an explicitly allowed value
            # is one a decision legitimately quotes.
            if (len(token) < 3 or token in names or token in allowed
                    or token.lower() == "nan" or _is_bare_integer(token)):
                continue
            if token in exact or any(token in line for line in prose):
                present += 1
        if present >= threshold:
            raise ArchiveError(
                f"{present} values from row {label!r} appear together in the "
                "serialized project — that row is partially reconstructible from "
                "the record. Persist decisions and inputs; regenerate derivatives.")


def assert_no_participant_data(
    serialized: Mapping[str, Any] | str,
    df: pd.DataFrame,
    *,
    allow: Iterable[str] = (),
) -> None:
    """No cell value from `df` may appear in the serialized project.

    The operational form of "never persist participant data". The project is a
    record of *decisions*; if a decision embeds the values it was made about,
    the record becomes an uncontrolled copy of the data and travels wherever the
    record travels.

    `allow` exempts values a decision legitimately quotes — a sentinel code that
    a methods sentence has to name, for instance. Every exemption is explicit,
    so the list is arguable rather than invisible.
    """
    blob = serialized if isinstance(serialized, str) else json.dumps(
        serialized, default=str)
    exact, prose = _leaves(blob)
    allowed = {str(a) for a in allow}
    leaked = sorted(v for v in _frame_cell_values(df)
                    if v not in allowed
                    and (v in exact or any(v in line for line in prose)))
    if leaked:
        raise ArchiveError(
            f"{len(leaked)} value(s) from the table appear in the serialized "
            f"project: {leaked[:8]}. Persist decisions and inputs; regenerate "
            "derivatives. If a decision legitimately quotes one of these, pass "
            "it in `allow` so the exemption is on the record.")


