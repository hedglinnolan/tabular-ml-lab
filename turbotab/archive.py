# Reading
# ─────────────────────────────────────────────────────────────────────────────

def from_bytes(raw: bytes):
    """Rebuild a project. Derivatives are recomputed, never read."""
    from turbotab.project import AnalysisProject

    if _looks_like_pickle(raw[:8]):
        raise ArchiveError("This file looks like a pickle. Archives are JSON and "
                           "parquet; a restore never executes code.")
    try:
        zf = zipfile.ZipFile(io.BytesIO(raw))
    except zipfile.BadZipFile as exc:
        raise ArchiveError("Not a readable archive.") from exc

    names = set(zf.namelist())
    if "manifest.json" not in names:
        raise ArchiveError("Archive has no manifest.")
    manifest = json.loads(zf.read("manifest.json"))
    version = str(manifest.get("schema_version", ""))
    if version not in ACCEPTED_SCHEMA_VERSIONS:
        raise ArchiveError(
            f"Archive schema {version!r} is not readable "
            f"(this writes {SAVE_SCHEMA_VERSION!r}, accepts "
            f"{sorted(ACCEPTED_SCHEMA_VERSIONS)}).")

    if "data/working_table.parquet" not in names:
        raise ArchiveError("Archive carries no table.")
    df = pd.read_parquet(io.BytesIO(zf.read("data/working_table.parquet")))

    config = json.loads(zf.read("config.json")) if "config.json" in names else {}
    project = AnalysisProject.from_dataframe(df, config.get("name") or "restored")
    project.id = config.get("project_id", project.id)
    project.created_at = config.get("created_at", project.created_at)
    project.target = config.get("target_col")
    project.task_type = config.get("task_type")
    project.task_confidence = config.get("task_confidence")
    project.task_overridden = bool(config.get("task_overridden", False))
    project.workflow_mode = config.get("workflow_mode", "quick")
    project.pipeline_specs = dict(config.get("pipeline_specs") or {})
    # `or None` would collapse a recorded empty list into "never asked", which
    # `normalize` already refuses to produce — but the archive must not be the
    # one place that can reintroduce the state.
    lens = config.get("lens")
    project.lens = list(lens) if isinstance(lens, list) else None
    project.orientation = config.get("orientation") or None
    project.purpose = config.get("purpose") or None
    project.repeat_kind = config.get("repeat_kind") or None
    project.unit_of_analysis = config.get("unit_of_analysis") or None
    project.aggregation = config.get("aggregation") or None
    project.temporal_prediction = config.get("temporal_prediction") or None
    project.grain = config.get("grain") or None
    project.eligibility = config.get("eligibility") or None
    project.obligations = list(config.get("obligations") or [])
    project.selected_models = list(config.get("selected_models") or [])
    project.preparation_mode = config.get("preparation_mode") or None
    project.model_recipes = dict(config.get("model_recipes") or {})
    project.missingness = list(config.get("missingness") or [])
    project.preprocess_settled = bool(config.get("preprocess_settled", False))
    project.engineered = list(config.get("engineered") or [])
    project.deferred_transforms = list(config.get("deferred_transforms") or [])
    project.selection_spec = config.get("selection_spec") or None
    project.features_settled = bool(config.get("features_settled", False))
    project.stale_downstream = list(config.get("stale_downstream") or [])

    if "lockbox.json" in names:
        project.lockbox = json.loads(zf.read("lockbox.json"))
    if "cohort.json" in names:
        project.cohort = json.loads(zf.read("cohort.json"))

    if "provenance.json" in names:
        from turbotab.project import Decision
        project.decisions = [
            Decision(id=d["id"], kind=d["kind"], subject=d.get("subject", ""),
                     text=d.get("text", ""), at=d.get("at", ""),
                     payload=d.get("payload") or {})
            for d in json.loads(zf.read("provenance.json"))
        ]

    # Derivatives were never written; they are stale by definition until
    # recomputed, and saying so is the honest state to restore into.
    project.findings, project.profile = [], None
    project.findings_stale = True
    return project
