def build_members(project) -> Dict[str, bytes]:
    """`{filename: bytes}` for every archive member, in `session_manager` order."""
    members: Dict[str, bytes] = {}
    saved: List[str] = []
    skipped: List[str] = []

    # --- the table --------------------------------------------------------
    if project.df is not None and len(project.df) > 0:
        buf = io.BytesIO()
        # index=True, unlike session_manager: row identity is the index label
        # (T0-ID-001), so dropping the index would throw away the thing the
        # lockbox and every recorded decision refer to.
        project.df.to_parquet(buf, index=True)
        members["data/working_table.parquet"] = buf.getvalue()
        saved.append("working_table")

    # --- config -----------------------------------------------------------
    config = {
        "project_id": project.id,
        "name": project.name,
        "created_at": project.created_at,
        "target_col": project.target,
        "task_type": project.task_type,
        "task_confidence": project.task_confidence,
        "task_overridden": bool(project.task_overridden),
        "row_identity": "index_labels",
        "workflow_mode": project.workflow_mode,
        # SPECS, never fitted objects. TRANSITION_PLAN §02.1: storing the fitted
        # pipeline let two models alias one instance, because the global slot
        # handed back the same object and page 06 fitted it in place.
        "pipeline_specs": {k: _json_safe(v)
                           for k, v in project.pipeline_specs.items()},
        # The Features step's decisions. Engineered columns are IN the parquet
        # already; what would be lost without these is the RECORD of how they
        # got there, and the deferred specs — which have no other home, because
        # nothing has executed them yet.
        "engineered": _json_safe(project.engineered),
        "deferred_transforms": _json_safe(project.deferred_transforms),
        "selection_spec": _json_safe(project.selection_spec) if project.selection_spec else None,
        "features_settled": bool(project.features_settled),
        "stale_downstream": _json_safe(project.stale_downstream),
        # The lens travels for the same reason the grain does, and for one more:
        # the structural diagnosis is READ under it, so a restored project that
        # lost the lens would recompute its findings under a different reading
        # of what the table is — and would do so silently, because the findings
        # are a regenerated derivative and would come back looking fresh.
        # `[]` and `None` are different answers here: `None` is never asked.
        "lens": list(project.lens) if project.lens is not None else None,
        # The orientation answer travels, and it is the sharpest case in this
        # config after `aggregation`: answering *features in rows* TRANSPOSED
        # the frame, and the parquet beside this holds the turned-around table.
        # A restored project that lost the record would hold sample-rows with
        # nothing saying they were ever columns — the receipt for an
        # irreversible operation, missing.
        "orientation": _json_safe(project.orientation) if project.orientation else None,
        # The purpose travels because the DEFAULTS downstream are read from it.
        # A restored project that lost it would silently revert to the app's old
        # assumption — prediction — and change what a dozen later questions
        # default to, with nothing saying so.
        "purpose": _json_safe(project.purpose) if project.purpose else None,
        # Questions 4 to 7. `aggregation` is the sharpest of the four: it is the
        # only one that CHANGED THE TABLE, and the parquet that travels beside
        # this config holds the combined rows. A restored project that lost the
        # record would hold a frame of person-rows with nothing saying they were
        # ever anything else — the receipt for an irreversible operation,
        # missing.
        "repeat_kind": _json_safe(project.repeat_kind) if project.repeat_kind else None,
        "unit_of_analysis": project.unit_of_analysis or None,
        "aggregation": _json_safe(project.aggregation) if project.aggregation else None,
        "temporal_prediction": (_json_safe(project.temporal_prediction)
                                if project.temporal_prediction else None),
        # The grain answer travels with the project, not just with the seal.
        # A restored project that has been sealed must not be able to answer
        # the question again, and one that has NOT been sealed must not be
        # asked twice — both need the answer itself, not only its consequence.
        "grain": _json_safe(project.grain) if project.grain else None,
        # The eligibility answer travels too, and for a sharper reason than
        # most: a restored project that lost it would ask the question again
        # AFTER its seal exists, which `set_eligibility` refuses — so the
        # project would be stuck with no way to say the step had happened.
        "eligibility": _json_safe(project.eligibility) if project.eligibility else None,
        # §05 spans two steps, so the obligation has to survive the gap
        # between them — including a save and a restore, which is the
        # longest form that gap takes.
        "obligations": _json_safe(project.obligations),
        # The Preprocess step is almost entirely DECLARATIONS, so the
        # archive is the only place they live: nothing has executed them,
        # and a restored project that lost them would have no record that
        # the step happened at all.
        "selected_models": [str(m) for m in project.selected_models],
        "preparation_mode": project.preparation_mode,
        "model_recipes": _json_safe(project.model_recipes),
        "missingness": _json_safe(project.missingness),
        "preprocess_settled": bool(project.preprocess_settled),
    }
    members["config.json"] = json.dumps(config, indent=2, default=str).encode("utf-8")
    saved.append("config")

    # --- lockbox (schema 2.1) --------------------------------------------
    if project.lockbox and project.lockbox.get("labels") is not None:
        lb = project.lockbox
        members["lockbox.json"] = json.dumps({
            "labels": [_plain_label(l) for l in lb["labels"]],
            "fraction": float(lb.get("fraction", 0.15)),
            "seed": int(lb.get("seed", 42)),
            "n_total": int(lb.get("n_total", 0)),
            "n_test": int(lb.get("n_test", len(lb["labels"]))),
            "signature": str(lb.get("signature", "")),
            "stratified": bool(lb.get("stratified", False)),
            "fraction_requested": float(lb.get("fraction_requested",
                                               lb.get("fraction", 0.15))),
            "target_col": str(lb.get("target_col") or ""),
            "strata": [str(c) for c in (lb.get("strata") or [])],
            "strata_requested": [str(c) for c in (lb.get("strata_requested") or [])],
            "group_col": str(lb["group_col"]) if lb.get("group_col") else None,
            "group_kind": str(lb["group_kind"]) if lb.get("group_kind") else None,
            "group_noun": str(lb["group_noun"]) if lb.get("group_noun") else None,
            "n_test_groups": (int(lb["n_test_groups"])
                              if lb.get("n_test_groups") is not None else None),
            # Constitution §03: the seal states its own basis. This member is
            # an explicit whitelist, so a basis added to the lockbox and not
            # added here is dropped on save — the seal would come back from
            # the archive unable to say what it rests on, which is precisely
            # the `group_col: None` ambiguity §03 exists to remove.
            "seal_basis": str(lb["seal_basis"]) if lb.get("seal_basis") else None,
            "basis_source": (str(lb["basis_source"])
                             if lb.get("basis_source") else None),
            "n_groups": (int(lb["n_groups"])
                         if lb.get("n_groups") is not None else None),
            "exploratory": bool(lb.get("exploratory", False)),
        }, indent=2).encode("utf-8")
        saved.append("test_lockbox")

    # --- the active cohort filter (schema 2.1) ---------------------------
    # ARCHITECTURE.md §02: a project that models "the working table" without
    # modeling "the active cohort filter" silently deletes the newest feature.
    if project.cohort and project.cohort.get("labels"):
        run = project.cohort
        members["cohort.json"] = json.dumps({
            "column": str(run["column"]),
            "value": _plain_label(run.get("value")),
            "label": str(run.get("label", "")),
            "labels": [_plain_label(x) for x in run["labels"]],
            "n_rows": int(run.get("n_rows", len(run["labels"]))),
            "n_total": int(run.get("n_total", 0)),
            "position": int(run.get("position", 1)),
            "of": int(run.get("of", 1)),
            "order": [str(x) for x in (run.get("order") or [])],
            "target_col": str(run.get("target_col") or ""),
            "dropped_features": [str(x) for x in (run.get("dropped_features") or [])],
        }, indent=2).encode("utf-8")
        saved.append("cohort_run")

    # --- the record -------------------------------------------------------
    members["provenance.json"] = json.dumps(
        [d.to_dict() for d in project.decisions], indent=2, default=str
    ).encode("utf-8")
    saved.append("decisions")

    # Derivatives are not written. The graph decides which those are, so a new
    # result key is dropped automatically instead of being remembered.
    from turbotab import cascade
    skipped.extend(sorted(cascade.all_result_keys()))

    members["manifest.json"] = json.dumps({
        "schema_version": SAVE_SCHEMA_VERSION,
        "saved_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "workflow_step": project.readiness().next_step().key
                         if project.readiness().next_step() else "complete",
        "saved_keys": sorted(set(saved)),
        "skipped_keys": sorted(set(skipped)),
        "members": sorted(members.keys()) + ["manifest.json"],
    }, indent=2).encode("utf-8")
    return members


def to_bytes(project) -> bytes:
    """Pack the project into a zip, manifest first so readers can stream it."""
    members = build_members(project)
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", compression=zipfile.ZIP_DEFLATED) as zf:
        zf.writestr("manifest.json", members.pop("manifest.json"))
        for name in sorted(members):
            zf.writestr(name, members[name])
    return buf.getvalue()


def serialized_json(project) -> str:
    """Every JSON member, as one document — what the guards inspect.

    One document rather than a concatenation, so the guards can parse it and
    compare values to values instead of searching raw text. The parquet member
    is excluded by construction: that is the table itself, travelling as the
    table, which is the user saving their own data.
    """
    members = build_members(project)
    return json.dumps({name: json.loads(raw.decode("utf-8"))
                       for name, raw in sorted(members.items())
                       if name.endswith(".json")}, indent=2)


